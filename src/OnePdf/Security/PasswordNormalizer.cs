    private static readonly Lazy<bool> NativeWorks = new(static () =>
    {
        try
        {
            return "\uFB01".Normalize(NormalizationForm.FormKC) == "fi";
        }
        catch (PlatformNotSupportedException)
        {
            return false;
        }
    });

    private static readonly Lazy<Dictionary<int, char>> Pairs = new(static () =>
    {
        var d = new Dictionary<int, char>(Base.Length);
        for (int i = 0; i < Base.Length; i++)
        {
            d[(Base[i] << 16) | Mark[i]] = Composed[i];
        }

        return d;
    });

    public static string NormalizeKc(string s)
    {
        if (NativeWorks.Value)
        {
            return s.Normalize(NormalizationForm.FormKC);
        }

        bool ascii = true;
        foreach (char c in s)
        {
            if (c > 0x7F)
            {
                ascii = false;
                break;
            }
        }

        if (ascii)
        {
            return s;
        }

        var sb = new StringBuilder(s.Length);
        foreach (char c in s)
        {
            if (c is >= '\uFF01' and <= '\uFF5E')
            {
                sb.Append((char)(c - 0xFEE0));
            }
            else if (c is >= '\uFB00' and <= '\uFB06')
            {
                sb.Append(c switch { '\uFB00' => "ff", '\uFB01' => "fi", '\uFB02' => "fl", '\uFB03' => "ffi", '\uFB04' => "ffl", _ => "st" });
            }
            else if (c is '\u2070' or (>= '\u2074' and <= '\u2079'))
            {
                sb.Append((char)('0' + (c == '\u2070' ? 0 : c - 0x2070)));
            }
            else if (c is >= '\u2080' and <= '\u2089')
            {
                sb.Append((char)('0' + (c - 0x2080)));
            }
            else
            {
                switch (c)
                {
                    case '\u00B2': sb.Append('2'); break;
                    case '\u00B3': sb.Append('3'); break;
                    case '\u00B9': sb.Append('1'); break;
                    case '\u00AA': sb.Append('a'); break;
                    case '\u00BA': sb.Append('o'); break;
                    case '\u00B5': sb.Append('\u03BC'); break;
                    default: sb.Append(c); break;
                }
            }
        }

        // Compose base letter + combining mark.
        var result = new StringBuilder(sb.Length);
        Dictionary<int, char> pairs = Pairs.Value;
        for (int i = 0; i < sb.Length; i++)
        {
            char c = sb[i];
            if (i + 1 < sb.Length && sb[i + 1] is >= '\u0300' and <= '\u036F' && pairs.TryGetValue((c << 16) | sb[i + 1], out char composed))
            {
                result.Append(composed);
                i++;
            }
            else
            {
                result.Append(c);
            }
        }

        return result.ToString();
    }
