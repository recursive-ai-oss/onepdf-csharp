#!/usr/bin/env python3
"""Generates src/OnePdf/Text/Extraction/FoldData.g.cs from the Unicode Character Database.

Input (Unicode 17.0.0, https://www.unicode.org/Public/17.0.0/ucd/): UnicodeData.txt.
Usage: python3 tools/fold/generate.py <dir containing UnicodeData.txt> > src/OnePdf/Text/Extraction/FoldData.g.cs

The table maps presentation forms and compatibility characters to the characters they stand for, using the full
(recursive) canonical and compatibility decomposition of UnicodeData.txt, for these blocks only:
  2E80-2EFF  CJK Radicals Supplement          F900-FAFF  CJK Compatibility Ideographs
  2F00-2FDF  Kangxi Radicals                  2F800-2FA1F CJK Compatibility Ideographs Supplement
  FB1D-FB4F  Hebrew presentation forms        FB50-FDFF  Arabic Presentation Forms-A
  FE70-FEFF  Arabic Presentation Forms-B
The Latin ligatures U+FB00-FB06 are left out: extraction decomposes them under its own option. Where a decomposition
starts with a no-break-style SPACE followed by a combining mark (the isolated Arabic diacritics), the space is dropped so
the mark follows the previous letter as it does in text.
"""
import sys
import unicodedata
from pathlib import Path

RANGES = [(0x2E80, 0x2EFF), (0x2F00, 0x2FDF), (0xF900, 0xFAFF), (0x2F800, 0x2FA1F), (0xFB1D, 0xFB4F), (0xFB50, 0xFDFF), (0xFE70, 0xFEFF)]

decomp = {}
for line in (Path(sys.argv[1]) / "UnicodeData.txt").read_text(encoding="utf-8").splitlines():
    f = line.split(";")
    if f[5]:
        parts = f[5].split()
        if parts[0].startswith("<"):
            parts = parts[1:]
        decomp[int(f[0], 16)] = [int(p, 16) for p in parts]

# Hebrew and CJK ranges contain unassigned code points; ranges are given by block, so only assigned ones appear.
def full(c, depth=0):
    d = decomp.get(c)
    if d is None or depth > 8:
        return [c]
    out = []
    for x in d:
        out.extend(full(x, depth + 1))
    return out

entries = []
for a, b in RANGES:
    for c in range(a, b + 1):
        if c not in decomp or 0xFB00 <= c <= 0xFB06:
            continue
        r = full(c)
        if len(r) > 1 and r[0] == 0x20 and unicodedata.combining(chr(r[1])) != 0:
            r = r[1:]
        if r == [c]:
            continue
        entries.append((c, r))
entries.sort()

keys = [c for c, _ in entries]
offsets = [0]
text = []
for _, r in entries:
    for x in r:
        if x >= 0x10000:
            y = x - 0x10000
            text.extend([0xD800 + (y >> 10), 0xDC00 + (y & 0x3FF)])
        else:
            text.append(x)
    offsets.append(len(text))

def ints(values, per=10):
    return ",\n        ".join(", ".join(f"0x{v:X}" for v in values[i:i + per]) for i in range(0, len(values), per))

print("// <auto-generated>Generated by tools/fold/generate.py from Unicode 17.0.0 UnicodeData.txt.</auto-generated>")
print("// Unicode data files: Copyright (c) 1991-2025 Unicode, Inc., distributed under the Unicode License v3 (see THIRD-PARTY-NOTICES.md).")
print("namespace OnePdf.Text;")
print()
print("internal static class FoldData")
print("{")
print("    /// <summary>The folded code points, ascending.</summary>")
print("    internal static ReadOnlySpan<int> Keys =>")
print("    [")
print("        " + ints(keys) + ",")
print("    ];")
print()
print("    /// <summary>For entry i, its replacement is <see cref=\"Text\"/>[Offsets[i]..Offsets[i + 1]] (UTF-16 code units).</summary>")
print("    internal static ReadOnlySpan<int> Offsets =>")
print("    [")
print("        " + ints(offsets) + ",")
print("    ];")
print()
print("    /// <summary>All replacements, one after the other, as UTF-16 code units.</summary>")
print("    internal static ReadOnlySpan<char> Text =>")
print("    [")
print("        " + ",\n        ".join(", ".join(f"(char)0x{v:X}" for v in text[i:i + 8]) for i in range(0, len(text), 8)) + ",")
print("    ];")
print("}")
