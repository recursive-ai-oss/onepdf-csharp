#!/usr/bin/env python3
"""Generates src/OnePdf/Text/Extraction/BidiData.g.cs from the Unicode Character Database.

Inputs (Unicode 16.0.0, https://www.unicode.org/Public/16.0.0/ucd/): extracted/DerivedBidiClass.txt and BidiBrackets.txt.
Usage: python3 tools/bidi/generate.py <dir containing the two files> > src/OnePdf/Text/Extraction/BidiData.g.cs
"""
import re
import sys
from pathlib import Path

NAMES = ["L", "R", "AL", "EN", "ES", "ET", "AN", "CS", "NSM", "BN", "B", "S", "WS", "ON",
         "LRE", "LRO", "RLE", "RLO", "PDF", "LRI", "RLI", "FSI", "PDI"]
LONG = {"Left_To_Right": "L", "Right_To_Left": "R", "Arabic_Letter": "AL", "European_Number": "EN",
        "European_Separator": "ES", "European_Terminator": "ET", "Arabic_Number": "AN", "Common_Separator": "CS",
        "Nonspacing_Mark": "NSM", "Boundary_Neutral": "BN", "Paragraph_Separator": "B", "Segment_Separator": "S",
        "White_Space": "WS", "Other_Neutral": "ON", "Left_To_Right_Embedding": "LRE", "Left_To_Right_Override": "LRO",
        "Right_To_Left_Embedding": "RLE", "Right_To_Left_Override": "RLO", "Pop_Directional_Format": "PDF",
        "Left_To_Right_Isolate": "LRI", "Right_To_Left_Isolate": "RLI", "First_Strong_Isolate": "FSI",
        "Pop_Directional_Isolate": "PDI"}

src = Path(sys.argv[1])
cls = [0] * 0x110000
for line in (src / "DerivedBidiClass.txt").read_text(encoding="utf-8").splitlines():
    m = re.match(r"# @missing: ([0-9A-F]+)\.\.([0-9A-F]+); (\w+)", line)
    if m:
        a, b, n = int(m[1], 16), int(m[2], 16), NAMES.index(LONG[m[3]])
        for c in range(a, b + 1):
            cls[c] = n
for line in (src / "DerivedBidiClass.txt").read_text(encoding="utf-8").splitlines():
    line = line.split("#")[0].strip()
    if not line:
        continue
    m = re.match(r"([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)", line)
    a = int(m[1], 16)
    b = int(m[2], 16) if m[2] else a
    n = NAMES.index(m[3])
    for c in range(a, b + 1):
        cls[c] = n

runs = []
start = 0
for c in range(1, 0x110001):
    if c == 0x110000 or cls[c] != cls[start]:
        runs.append((start, c - 1, cls[start]))
        start = c
# class L is the default; leave it out of the table
runs = [r for r in runs if r[2] != 0]

brackets = []
for line in (src / "BidiBrackets.txt").read_text(encoding="utf-8").splitlines():
    line = line.split("#")[0].strip()
    if not line:
        continue
    a, b, t = [x.strip() for x in line.split(";")]
    brackets.append((int(a, 16), int(b, 16), 1 if t == "o" else 2))

out = []
out.append("// <auto-generated>Generated by tools/bidi/generate.py from Unicode 16.0.0 DerivedBidiClass.txt and BidiBrackets.txt.</auto-generated>")
out.append("// Unicode data files: Copyright (c) 1991-2024 Unicode, Inc., distributed under the Unicode License v3 (see THIRD-PARTY-NOTICES.md).")
out.append("namespace OnePdf.Text;")
out.append("")
out.append("internal static class BidiData")
out.append("{")
out.append("    /// <summary>Triples of (first code point, last code point, Bidi_Class) for every range whose class is not L; ordered by code point.</summary>")
out.append("    internal static ReadOnlySpan<int> ClassRanges =>")
out.append("    [")
for i in range(0, len(runs), 6):
    out.append("        " + ", ".join(f"0x{a:X}, 0x{b:X}, {n}" for a, b, n in runs[i:i + 6]) + ",")
out.append("    ];")
out.append("")
out.append("    /// <summary>Triples of (code point, Bidi_Paired_Bracket, type: 1 open, 2 close) ordered by code point.</summary>")
out.append("    internal static ReadOnlySpan<int> Brackets =>")
out.append("    [")
for i in range(0, len(brackets), 6):
    out.append("        " + ", ".join(f"0x{a:X}, 0x{b:X}, {t}" for a, b, t in brackets[i:i + 6]) + ",")
out.append("    ];")
out.append("}")
print("\n".join(out))
